CS.colorOfEff = function (g, eff) {
  var e = CS.resolveEff(g, eff);
  var order = ['study', 'create', 'social', 'body', 'exp'];
  for (var i = 0; i < order.length; i++) { if (e[order[i]] > 0) { return order[i]; } }
  return (e.stress < 0) ? 'rest' : 'stress';
};
