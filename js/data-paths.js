CS.majorOf = function (majorId) {
  for (var i = 0; i < CS.COLLEGES.length; i++) {
    var c = CS.COLLEGES[i];
    for (var j = 0; j < c.majors.length; j++) {
      var m = c.majors[j];
      if (m[0] === majorId) { return { id: m[0], name: m[1], field: m[2], req: m[3], recs: m[4], college: c }; }
    }
  }
  return null;
};
CS.rowOf = function (list, id) {
  for (var i = 0; i < list.length; i++) { if (list[i][0] === id) { return list[i]; } }
  return null;
};
