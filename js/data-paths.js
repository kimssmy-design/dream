CS.majorsInField = function (fieldId, max) {
  var out = [];
  for (var i = 0; i < CS.COLLEGES.length; i++) {
    for (var j = 0; j < CS.COLLEGES[i].majors.length; j++) {
      var m = CS.COLLEGES[i].majors[j];
      if (m[2] === fieldId && out.length < max) { out.push(m); }
    }
  }
  return out;
};

