/* 직업 하나 찾기 */
CS.jobOf = function (fieldId, idx) {
  var j = CS.FIELDS[fieldId].jobs[idx];
  return { name: j[0], desc: j[1], style: j[2] };
};
/* 전체 엔딩(직업) 수 */
CS.jobCount = function () {
  var n = 0;
  for (var k in CS.FIELDS) { if (CS.FIELDS.hasOwnProperty(k)) { n += CS.FIELDS[k].jobs.length; } }
  return n;
};
